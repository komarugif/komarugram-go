// Gen compiles scale.comp to SPIR-V with glslc (shaderc) and writes it into
// ../scale_spv.h as words for hwvk_linux.c: the build compiles no shader.
// Run from pkg/hwvideo with `go generate`; glslc must be on the PATH (the
// Vulkan SDK, or the shaderc package of a distribution).
package main

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"komarugram/pkg/program"
)

func main() {
	glslc, err := program.LookPath("glslc")
	if err != nil {
		log.Fatal("gen: no glslc on the PATH: ", err)
	}
	tmp, err := os.MkdirTemp("", "scale-spv")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmp)
	out := filepath.Join(tmp, "scale.spv")
	src := filepath.Join("shaders", "scale.comp")
	cmd := program.Command(glslc, "--target-env=vulkan1.0", "-O", "-o", out, src)
	if msg, err := cmd.CombinedOutput(); err != nil {
		log.Fatalf("gen: glslc: %v\n%s", err, msg)
	}
	version, err := program.Command(glslc, "--version").Output()
	if err != nil {
		log.Fatal("gen: glslc --version: ", err)
	}
	spv, err := os.ReadFile(out)
	if err != nil {
		log.Fatal(err)
	}
	if len(spv)%4 != 0 || len(spv) < 20 || binary.LittleEndian.Uint32(spv) != 0x07230203 {
		log.Fatalf("gen: glslc wrote no SPIR-V (%d bytes)", len(spv))
	}
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: Unlicense OR MIT\n\n")
	b.WriteString("// Code generated by shaders/gen.go from shaders/scale.comp; DO NOT EDIT.\n")
	// glslc tells its own version, then those of SPIRV-Tools and glslang.
	lines := strings.Fields(strings.TrimSpace(string(version)))
	for len(lines) < 3 {
		lines = append(lines, "?")
	}
	fmt.Fprintf(&b, "// Compiled with glslc (shaderc) %s, SPIRV-Tools %s, glslang %s: --target-env=vulkan1.0 -O.\n\n", lines[0], lines[1], lines[2])
	b.WriteString("static const uint32_t hwvk_scale_spv[] = {")
	for i := 0; i < len(spv); i += 4 {
		if i%32 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "0x%08x,", binary.LittleEndian.Uint32(spv[i:]))
	}
	b.WriteString("\n};\n")
	if err := os.WriteFile("scale_spv.h", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
